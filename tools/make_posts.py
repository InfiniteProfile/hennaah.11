#!/usr/bin/env python3
"""Optional helper: regenerate posts.js from tools/filenames.txt (one filename per line).

Grouping rule (inferred, NOT confirmed by Instagram metadata):
  igexport-<11-char shortcode>[-N].<ext>  ->  files sharing a shortcode become ONE carousel.
  The file without a -N suffix is item 1; -2, -3 ... follow in numeric order.
  "name (1).ext" copies are kept as separate posts (id "<shortcode>-copy1").
Order (inferred): shortcodes are base64-encoded media IDs that grow over time, so posts are
  sorted newest first by decoding the shortcode. This is not an original-order guarantee.
Edit posts.js by hand afterwards if a group is wrong; use overrides.js for captions/dates.
"""
import re, json, sys, collections, pathlib
here = pathlib.Path(__file__).parent
ALPHA = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_"
def decode(code):
    n = 0
    for ch in code: n = n * 64 + ALPHA.index(ch)
    return n
VIDEO = re.compile(r"\.(mp4|webm)$", re.I)
lines = [l.rstrip("\r\n") for l in (here / "filenames.txt").read_text(encoding="utf-8").splitlines() if l.strip()]
groups = collections.OrderedDict(); problems = []
seen = collections.Counter(lines)
for l in lines:
    if seen[l] > 1: problems.append("duplicate filename: " + l)
    stem = l.rsplit(".", 1)[0]
    if not stem.startswith("igexport-"): problems.append("unrecognised name: " + l); stem = "x-" + stem
    s = stem[len("igexport-"):]
    copy = 0
    m = re.search(r" \((\d+)\)$", s)
    if m: copy = int(m.group(1)); s = s[:m.start()]
    m = re.fullmatch(r"(.{11})(?:-(\d+))?", s)
    if not m: problems.append("unrecognised shortcode: " + l); code, idx = s, 1
    else: code, idx = m.group(1), int(m.group(2) or 1)
    key = (code, copy)
    groups.setdefault(key, []).append((idx, l))
def sortkey(k):
    try: return (-decode(k[0]), k[1])
    except ValueError: return (0, k[1])
out = []
for key in sorted(groups, key=sortkey):
    code, copy = key
    files = [f for _, f in sorted(groups[key])]
    kinds = {bool(VIDEO.search(f)) for f in files}
    t = "carousel" if len(files) > 1 else ("video" if kinds == {True} else "image")
    out.append({"id": code if not copy else f"{code}-copy{copy}", "type": t, "files": files, "caption": "", "timestamp": ""})
ids = [p["id"] for p in out]; assert len(ids) == len(set(ids))
assert sum(len(p["files"]) for p in out) == len(lines)
body = ",\n".join("  " + json.dumps(p, ensure_ascii=False) for p in out)
(here.parent / "posts.js").write_text(
 "/* Generated by tools/make_posts.py from tools/filenames.txt. Safe to edit by hand.\n"
 "   Each post's `files` array is its carousel grouping. Captions/dates: use overrides.js. */\n"
 'const MEDIA_BASE = "https://raw.githubusercontent.com/InfiniteProfile/hennaah.11/main/";\n'
 'const PROFILE_DIR = "profile photo/";\n'
 'const PROFILE = {\n  name: "Hena",\n  username: "hennaah.11",\n  photo: "igexport-DVY7NlejDJ9-6.jpg",\n  bio: "",\n  followers: null,\n  following: null\n};\n\n'
 "const posts = [\n" + body + "\n];\n", encoding="utf-8")
c = collections.Counter(p["type"] for p in out)
print(f"{len(lines)} filenames -> {len(out)} posts {dict(c)}; problems: {problems or 'none'}")
